#include <stdio.h>

int main() {
    int x = 10; // Initialised with example values
    int y = 20;

    if (x > y) {
        printf("x is greater than y");
    } 
    else if (x < y) {
        printf("x is less than y");
    } 
    else {
        printf("x is equal to y");
    }

    return 0; // Corrected lowercase 'return'
}
