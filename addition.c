#include <stdio.h>

int main() {
    // Declare and initialize the two integer variables
    int x = 5;
    int y = 6;
    
    // Calculate the sum
    int sum = x + y;
    
    // Print the result to the console
    printf("The sum of %d and %d is: %d\n", x, y, sum);
    
    return 0;
}
